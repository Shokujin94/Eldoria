// Runs in CI against a temporary DB. No production accounts or deployment.
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { createServer } from 'node:net';
import assert from 'node:assert/strict';
const dir=await mkdtemp(join(tmpdir(),'eldoria-browser-'));
const probe=createServer();probe.listen(0,'127.0.0.1');await once(probe,'listening');const chosenPort=probe.address().port;await new Promise((resolve,reject)=>probe.close(e=>e?reject(e):resolve()));
const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,DB_PATH:join(dir,'test.sqlite'),PORT:String(chosenPort),HOST:'127.0.0.1',ALLOWED_ORIGINS:'http://127.0.0.1:'+chosenPort,SERVE_PREVIEW:'1',REGISTRATION_MODE:'open'},stdio:['ignore','pipe','pipe']});
let browser;
try{
 const port=await new Promise((resolve,reject)=>{let log='';const timer=setTimeout(()=>reject(Error('startup timeout')),10000);child.stdout.on('data',d=>{log+=d;const m=log.match(/Eldoria online API (\d+)/);if(m){clearTimeout(timer);resolve(+m[1]);}});child.once('exit',c=>{clearTimeout(timer);reject(Error('server exit '+c));});});
 browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')console.log('browser:',m.text());});
 await page.goto('http://127.0.0.1:'+port);
 await page.locator('#auth input[name=username]').fill('browser_test');
 await page.locator('#auth input[name=password]').fill('Senha teste browser 123!');
 await page.locator('#auth button[value=register]').click();
 await page.locator('#recovery54-dialog[open]').waitFor();
 await page.locator('#code54-close').click();
 await page.locator('#character input[name=name]').fill('Herói Teste');
 await page.locator('[data-cls61=necro]').click();
 await page.locator('#character button').last().click();
 await page.locator('#journey61').waitFor({state:'visible'});
 assert.match(await page.locator('#hero').innerText(),/Necromante/);
 await page.locator('[data-tab=character]').click();
 await page.locator('[data-character61=gear]').click();
 await page.locator('.paper61-hero').waitFor();
 await page.locator('[data-tab=bag]').click();
 await page.locator('[data-filter61=weapon]').click();
 await page.locator('[data-filter61=weapon][aria-pressed=true]').waitFor();
 assert.equal(await page.locator('.bag56').count(),1);
 await page.locator('[data-tab=talent]').click();
 await page.locator('[data-path61]').first().waitFor();
 await page.locator('[data-tab=market]').click();
 await page.locator('#listing').waitFor();
 await page.locator('[data-tab=ranking]').click();
 await page.locator('#rankcat').waitFor();
 await page.locator('#window53-close').click();
 await page.locator('[data-mode61=gather]').click();
 await page.locator('#start61').click();
 await page.waitForFunction(()=>document.getElementById('world52-location').textContent.includes('Bosque'));
 await page.locator('[data-quick61=stop]').click();
 await page.waitForFunction(()=>document.getElementById('world52-location').textContent.includes('Vespera'));
 await page.locator('[data-mode61=hunt]').click();
 await page.locator('#start61').click();
 await page.locator('#target60').waitFor({state:'visible'});
 await page.locator('[data-quick61=stop]').click();
 await page.locator('#city61').waitFor({state:'visible'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),true,'mobile overflow');
 assert.deepEqual(errors,[]);
 console.log('Browser smoke: registration, vocation, character, bag, talents, market, ranking, gathering, hunt, return, mobile passed');
}finally{await browser?.close();if(child.exitCode===null){child.kill('SIGTERM');await once(child,'exit');}await rm(dir,{recursive:true,force:true});}
